import streamlit as st

from demo_content import (
    ASSET,
    EVIDENCE,
    QUESTIONS,
    SAMPLE_DOCUMENT,
    build_sample_report,
    compare_threshold,
    get_prepared_answer,
)


st.set_page_config(
    page_title="Sovereign AI Workbench | Public Demo",
    page_icon="🛡️",
    layout="wide",
)

st.markdown(
    """
    <style>
    .demo-banner {
        padding: 1rem 1.2rem;
        border: 1px solid #e6a23c;
        border-radius: 0.6rem;
        background: #fff7e6;
        color: #573600;
        font-weight: 650;
    }
    .muted { color: #596579; }
    </style>
    """,
    unsafe_allow_html=True,
)

st.title("🛡️ Sovereign AI Workbench")
st.caption("Public, synthetic-data demonstration of a local-first industrial workflow")
st.markdown(
    '<div class="demo-banner">SIMULATED DEMONSTRATION — '
    "Answers are prepared sample outputs, not live AI inference. "
    "No Ollama, external AI API, document upload, or private project data is used.</div>",
    unsafe_allow_html=True,
)

dashboard, workspace, verification, reports, architecture = st.tabs(
    ["Dashboard", "Task workspace", "Verification", "Sample report", "Architecture"]
)

with dashboard:
    st.header("A private-by-design local workbench, demonstrated safely")
    st.write(
        "The full local application analyzes documents with Ollama on your own computer. "
        "This hosted companion is intentionally read-only and uses only the synthetic "
        "training record shown below."
    )
    overview = st.columns(4)
    overview[0].metric("Demo mode", "SIMULATED")
    overview[1].metric("Sample asset", ASSET["tag"])
    overview[2].metric("Prepared evidence items", len(EVIDENCE))
    overview[3].metric("Live model calls", "None")

    st.subheader("Sample asset")
    st.write(
        f"**{ASSET['tag']}** · {ASSET['type']} · {ASSET['location']} · "
        f"inspection date {ASSET['inspection_date']}"
    )
    st.caption(f"Source document: {SAMPLE_DOCUMENT} — entirely synthetic training data.")

    st.subheader("Workflow")
    st.markdown(
        "1. Select a prepared industrial question.  \n"
        "2. Review the fixed sample answer and its source excerpts.  \n"
        "3. Inspect the deterministic numeric check and review flags.  \n"
        "4. Preview or download a sample report."
    )

with workspace:
    st.header("Industrial task workspace")
    question = st.selectbox("Choose a sample task", QUESTIONS)
    result = get_prepared_answer(question)
    st.markdown("#### Prepared sample response")
    st.info(result["answer"])
    st.caption("Prepared demonstration content — not generated by a live model.")

    col_facts, col_inferences, col_unknowns = st.columns(3)
    with col_facts:
        st.markdown("**Documented facts**")
        for item in result["facts"]:
            st.markdown(f"- {item}")
    with col_inferences:
        st.markdown("**Derived inferences**")
        if result["inferences"]:
            for item in result["inferences"]:
                st.markdown(f"- {item}")
        else:
            st.markdown("- None in this prepared answer.")
    with col_unknowns:
        st.markdown("**Unknown / not established**")
        for item in result["unknowns"]:
            st.markdown(f"- {item}")

    evidence_by_id = {item["id"]: item for item in EVIDENCE}
    st.markdown("#### Supporting evidence")
    st.caption(f"Source: {SAMPLE_DOCUMENT}")
    for evidence_id in result["evidence_ids"]:
        evidence = evidence_by_id[evidence_id]
        with st.expander(f"{evidence['id']} · {evidence['section']}", expanded=True):
            st.write(evidence["excerpt"])

with verification:
    st.header("Verification dashboard")
    check = compare_threshold(7.8, 7.1)
    metric_a, metric_b, metric_c = st.columns(3)
    metric_a.metric("Measured vibration", f"{check['reading']:.1f} mm/s RMS")
    metric_b.metric("Synthetic alert threshold", f"{check['threshold']:.1f} mm/s RMS")
    metric_c.metric("Deterministic check", check["status"])
    st.write(
        f"Python comparison: **{check['reading']:.1f} > {check['threshold']:.1f}** "
        f"is **{check['exceeded']}**. Readings above this exercise threshold are "
        "classified for investigation."
    )
    st.caption("This training threshold is not an approved site or manufacturer limit.")

    st.subheader("Grounding and review checks")
    st.write("**Document grounding:** Evidence IDs are attached to each prepared answer.")
    st.write("**Contradictions:** None encoded in this synthetic sample record.")
    st.write(
        "**Unsupported-claim example:** “The root cause is bearing failure” is not "
        "supported by the source excerpts and must not be treated as a finding."
    )
    st.warning("Human review: required and pending. No operational authorization is provided.")

with reports:
    st.header("Sample report")
    st.caption("Preview and download use only the synthetic training record.")
    st.markdown(f"**Source:** {SAMPLE_DOCUMENT}")
    st.markdown(get_prepared_answer(QUESTIONS[5])["answer"])
    st.markdown(
        f"**Threshold result:** {check['reading']:.1f} vs "
        f"{check['threshold']:.1f} mm/s RMS — {check['status']}"
    )
    st.markdown("**Human review:** Required and pending.")
    st.download_button(
        "Download synthetic sample report (DOCX)",
        data=build_sample_report(),
        file_name="sovereign_ai_synthetic_demo_report.docx",
        mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    )
    st.caption("The report is generated in memory and is not saved to persistent storage.")

with architecture:
    st.header("Hybrid architecture")
    st.subheader("Private local application")
    st.code(
        "User Interface → Document Ingestion → Retrieval → Local Ollama LLM\n"
        "              → Verification → Human Review → Report Generation",
        language="text",
    )
    st.write(
        "The Windows application retains local document ingestion and retrieval, "
        "SQLite persistence, localhost-only Ollama inference, verification, audit "
        "logging, human approval, and report generation."
    )

    st.subheader("Public simulated demonstration")
    st.code(
        "Streamlit UI → fixed synthetic sample record → prepared answers\n"
        "            → deterministic Python threshold check → in-memory DOCX",
        language="text",
    )
    st.write(
        "The public app does not import the local workbench modules, connect to "
        "Ollama, call an AI API, accept uploaded documents, or use the local database."
    )
    st.warning(
        "Streamlit Community Cloud is public cloud hosting; it is not an air-gapped "
        "environment. Never submit confidential or operational documents here."
    )
